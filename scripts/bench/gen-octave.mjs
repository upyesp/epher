#!/usr/bin/env node
// Generates the GNU Octave implementation files for the calculator benchmark
// (stage 3). The timed expression text is byte-identical to the canonical
// dataset; the only additions are the assignment prefix, the tic/toc timer,
// and (in verify files) the result vector dump. Committed outputs are the
// artifacts anyone can read (plan rule: implementations are committed files).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const dataDir = join(root, "scripts", "bench", "data");
const outDir = join(root, "scripts", "bench", "implementations", "octave");
mkdirSync(outDir, { recursive: true });

function batch(sourceFile, outName, task) {
  const lines = readFileSync(sourceFile, "utf8").split("\n").filter((l) => l.trim());
  const body = lines.map((l) => `__r = ${l};`).join("\n");
  const srcName = sourceFile.split("/").pop();
  const m = `% Calculator benchmark ${task}: canonical expressions as statements.
% Generated by scripts/bench/gen-octave.mjs from ${srcName}. Do not edit.
% Boundary: the driver times run('this file') with tic/toc from outside, so
% the span covers file read + parse + evaluation of every statement.
% This file contains no timer of its own.
${body}
`;
  writeFileSync(join(outDir, outName), m);
  console.log(`${outName}: ${lines.length} statements`);
}

function verify(sourceFile, outName, task) {
  const lines = readFileSync(sourceFile, "utf8").split("\n").filter((l) => l.trim());
  const body = lines.map((l, i) => `V(${i + 1}) = ${l};`).join("\n");
  const srcName = sourceFile.split("/").pop();
  const m = `% Calculator benchmark ${task} verification run (untimed; gate input).
% Generated by scripts/bench/gen-octave.mjs from ${srcName}. Do not edit.
V = zeros(1, ${lines.length});
${body}
out = getenv('BENCH_VERIFY_OUT');
fid = fopen(out, 'w');
fprintf(fid, '%.17g\\n', V);
fclose(fid);
printf('VERIFY_WRITTEN %d\\n', ${lines.length});
`;
  writeFileSync(join(outDir, outName), m);
  console.log(`${outName}: ${lines.length} values`);
}

batch(join(dataDir, "W1-expressions.txt"), "w1-batch.m", "W1 scalar arithmetic");
batch(join(dataDir, "W2-transcendental.txt"), "w2-batch.m", "W2 transcendental microbench");
verify(join(dataDir, "W1-expressions.txt"), "w1-verify.m", "W1");
verify(join(dataDir, "W2-transcendental.txt"), "w2-verify.m", "W2");
